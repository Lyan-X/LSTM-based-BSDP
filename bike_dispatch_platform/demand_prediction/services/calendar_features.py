def attach_temporal_features(frame: pd.DataFrame) -> pd.DataFrame:
    enriched = frame.copy()
    enriched["hour"] = pd.to_datetime(enriched["hour"])
    enriched["hour_of_day"] = enriched["hour"].dt.hour.astype(int)
    enriched["day_of_week"] = enriched["hour"].dt.dayofweek.astype(int)
    enriched["is_holiday"] = enriched["hour"].dt.date.map(lambda value: 1 if value in CHINA_HOLIDAYS else 0).astype(int)
    enriched["hour_sin"] = np.sin(2 * np.pi * enriched["hour_of_day"] / 24.0)
    enriched["hour_cos"] = np.cos(2 * np.pi * enriched["hour_of_day"] / 24.0)
    enriched["weekday_sin"] = np.sin(2 * np.pi * enriched["day_of_week"] / 7.0)
    enriched["weekday_cos"] = np.cos(2 * np.pi * enriched["day_of_week"] / 7.0)
    return enriched
